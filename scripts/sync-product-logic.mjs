#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// jobsafe — sync the product's own logic into lib/product-logic/.
//
// The free tools on the site (the RIDDOR checker, the 5×5 matrix) are the
// platform's own logic, published. They must never disagree with the app, so
// the files under lib/product-logic/ are COPIED from the product repository by
// this script, never edited by hand. Each copy starts with a header naming the
// source repository, the source path and the commit it was taken from.
//
//   node scripts/sync-product-logic.mjs --from ../jobsafe
//   node scripts/sync-product-logic.mjs --from ../jobsafe --check   # exit 1 if out of date
//
// What is taken (see docs/PRODUCT-LOGIC.md):
//   src/lib/domain/riddor/knowledge.ts  → lib/product-logic/riddor-knowledge.ts   (whole file)
//   src/lib/domain/risk/scoring.ts      → lib/product-logic/risk-scoring.ts       (BANDS, LIKELIHOOD_SCALE,
//                                          SEVERITY_SCALE, HIERARCHY_DEFS, clamp, score, bandOf only)
//   src/lib/domain/enums.ts             → lib/product-logic/enums.ts              (HIERARCHY, RIDDOR_CATEGORIES)
//   src/lib/format/date.ts              → lib/product-logic/date.ts               (calendar-date helpers)
// plus lib/product-logic/SOURCE.json, the manifest the `--check` mode compares.
//
// Imports are rewritten to relative `.ts` paths so Node's test runner can load
// the files without a bundler (the site's tests run on Node's type stripping).
// ─────────────────────────────────────────────────────────────────────────────

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..')
const args = process.argv.slice(2)
const arg = (name, fallback) => {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
const FROM = resolve(ROOT, arg('--from', '../jobsafe'))
const CHECK = args.includes('--check')
const OUT = join(ROOT, 'lib', 'product-logic')
const REPO = 'Jobmate-ltd/jobsafe'

if (!existsSync(join(FROM, 'src', 'lib', 'domain'))) {
  console.error(`sync-product-logic: no jobsafe checkout at ${FROM} (pass --from)`)
  process.exit(2)
}

const sha = execFileSync('git', ['-C', FROM, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
const today = new Date()
const synced = `${String(today.getDate()).padStart(2, '0')}/${String(today.getMonth() + 1).padStart(2, '0')}/${today.getFullYear()}`
const read = (rel) => readFileSync(join(FROM, rel), 'utf8')
const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16)

function header(sourcePath, note) {
  return [
    '// GENERATED by scripts/sync-product-logic.mjs — do not edit by hand.',
    `// Source: ${REPO} ${sourcePath} at commit ${sha}`,
    `// Synced ${synced}. Re-sync: node scripts/sync-product-logic.mjs --from ../jobsafe`,
    note ? `// ${note}` : null,
    '',
  ]
    .filter((line) => line !== null)
    .join('\n')
}

/** Extracts a top-level declaration (`export const X = …;` / `export type X = …;` / `[export] function x(…) {…}`) by name. */
function declaration(source, name) {
  // One-line declarations first (an arrow function, a regex, a type alias), then multi-line
  // literals that close on a line of their own.
  const patterns = [
    new RegExp(`^(?:export )?const ${name}\\b[^\\n]*;\\s*$`, 'm'),
    new RegExp(`^(?:export )?type ${name}\\b[^\\n]*;\\s*$`, 'm'),
    new RegExp(`^(?:export )?const ${name}\\b[^\\n]*=\\s*(?:\\[|\\{|\\()[^\\n]*\\n[\\s\\S]*?^(?:\\]|\\}|\\))(?: as const)?;\\s*$`, 'm'),
  ]
  for (const pattern of patterns) {
    const m = pattern.exec(source)
    if (m) return m[0].trimEnd()
  }
  // Functions: match the signature line then balance braces.
  const fn = new RegExp(`^(?:export )?function ${name}\\(`, 'm').exec(source)
  if (!fn) throw new Error(`sync-product-logic: cannot find ${name} in source`)
  // The body opens with the first `{` that ends a line (a return type may hold braces of its own).
  let i = source.indexOf('{\n', fn.index)
  let depth = 0
  for (; i < source.length; i++) {
    if (source[i] === '{') depth++
    else if (source[i] === '}') {
      depth--
      if (depth === 0) break
    }
  }
  // Include the JSDoc comment directly above, if any.
  const before = source.slice(0, fn.index)
  // Only a JSDoc block that sits directly above the signature (no `*/` inside it).
  const doc = /\/\*\*(?:(?!\*\/)[\s\S])*\*\/\s*$/.exec(before)
  const start = doc ? fn.index - doc[0].length : fn.index
  return source.slice(start, i + 1).trim()
}

const outputs = {}

// 1. RIDDOR knowledge: the whole file, imports rewritten.
{
  const src = 'src/lib/domain/riddor/knowledge.ts'
  let text = read(src)
  text = text.replace("import type { RiddorCategory } from '../enums';", "import type { RiddorCategory } from './enums.ts';")
  text = text.replace("import { addCalendarDays, calendarDaysBetween } from '@/lib/format/date';", "import { addCalendarDays, calendarDaysBetween } from './date.ts';")
  if (!/from '\.\/enums\.ts'/.test(text) || !/from '\.\/date\.ts'/.test(text)) throw new Error('sync-product-logic: knowledge.ts imports changed; update the rewrite rules')
  outputs['riddor-knowledge.ts'] = { src, text: header(src, 'Whole file. RIDDOR 2013 categories, specified injuries, diseases, dangerous occurrences, record duties, HSE contact, deadlines and the triage sequence.') + text }
}

// 2. Risk scoring: the 5×5 constants and the two scoring functions only.
{
  const src = 'src/lib/domain/risk/scoring.ts'
  const text = read(src)
  const parts = ['RiskBand', 'BandDef', 'BANDS', 'LIKELIHOOD_SCALE', 'SEVERITY_SCALE', 'HIERARCHY_DEFS', 'clamp', 'score', 'bandOf'].map((name) => {
    if (name === 'BandDef') {
      const m = /^export interface BandDef \{[\s\S]*?^\}/m.exec(text)
      if (!m) throw new Error('sync-product-logic: BandDef not found')
      return m[0]
    }
    return declaration(text, name)
  })
  const body = `import type { Hierarchy } from './enums.ts';\n\n${parts.join('\n\n')}\n`
  outputs['risk-scoring.ts'] = { src, text: header(src, 'Partial: BANDS, LIKELIHOOD_SCALE, SEVERITY_SCALE, HIERARCHY_DEFS, clamp, score and bandOf. The hazard, assessment and bowtie maths stay in the product.') + body }
}

// 3. Enums: only what the two files above need.
{
  const src = 'src/lib/domain/enums.ts'
  const text = read(src)
  const parts = ['HIERARCHY', 'Hierarchy', 'RIDDOR_CATEGORIES', 'RiddorCategory'].map((name) => declaration(text, name))
  outputs['enums.ts'] = { src, text: header(src, 'Partial: HIERARCHY / Hierarchy and RIDDOR_CATEGORIES / RiddorCategory.') + parts.join('\n\n') + '\n' }
}

// 4. Calendar-date helpers.
{
  const src = 'src/lib/format/date.ts'
  const text = read(src)
  const parts = ['pad2', 'CalendarDate', 'CAL', 'parseCalendar', 'fromUtc', 'toUtc', 'todayLocal', 'addCalendarDays', 'calendarDaysBetween'].map((name) => declaration(text, name))
  // The product keeps fromUtc/toUtc private; the tools need only the exported helpers.
  outputs['date.ts'] = { src, text: header(src, 'Partial: the calendar-date helpers (YYYY-MM-DD, no time, no zone) that riddorDeadline() depends on.') + parts.join('\n\n') + '\n' }
}

const manifest = {
  repo: REPO,
  commit: sha,
  synced,
  files: Object.fromEntries(Object.entries(outputs).map(([name, { src, text }]) => [name, { source: src, sourceHash: hash(read(src)), outputHash: hash(text.replace(/^\/\/ Synced .*$/m, '')) }])),
  sourceTests: {
    'src/lib/domain/riddor/knowledge.test.ts': hash(read('src/lib/domain/riddor/knowledge.test.ts')),
    'src/lib/domain/risk/scoring.test.ts': hash(read('src/lib/domain/risk/scoring.test.ts')),
  },
}

if (CHECK) {
  const current = existsSync(join(OUT, 'SOURCE.json')) ? JSON.parse(readFileSync(join(OUT, 'SOURCE.json'), 'utf8')) : null
  const stale = []
  for (const [name, entry] of Object.entries(manifest.files)) {
    if (!current?.files?.[name] || current.files[name].sourceHash !== entry.sourceHash) stale.push(`${name} (source ${entry.source} changed)`)
    else if (!existsSync(join(OUT, name)) || hash(readFileSync(join(OUT, name), 'utf8').replace(/^\/\/ Synced .*$/m, '')) !== entry.outputHash) stale.push(`${name} (local copy differs from what the script would write)`)
  }
  for (const [test, h] of Object.entries(manifest.sourceTests)) {
    if (current?.sourceTests?.[test] !== h) stale.push(`${test} changed upstream: re-check test/product-logic.test.mjs`)
  }
  if (stale.length) {
    console.error(`✘ lib/product-logic is out of date against ${REPO} ${sha.slice(0, 7)}:\n  ${stale.join('\n  ')}\nRun: node scripts/sync-product-logic.mjs --from ${arg('--from', '../jobsafe')}`)
    process.exit(1)
  }
  console.log(`✔ lib/product-logic matches ${REPO} ${sha.slice(0, 7)}`)
  process.exit(0)
}

mkdirSync(OUT, { recursive: true })
for (const [name, { text }] of Object.entries(outputs)) writeFileSync(join(OUT, name), text)
writeFileSync(join(OUT, 'SOURCE.json'), JSON.stringify(manifest, null, 2) + '\n')
console.log(`✔ synced ${Object.keys(outputs).length} files from ${REPO} ${sha.slice(0, 7)} into lib/product-logic/ (${synced})`)
console.log('  Now re-check test/product-logic.test.mjs against the upstream tests if SOURCE.json says they changed.')
